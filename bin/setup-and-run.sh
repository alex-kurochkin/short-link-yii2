#!/bin/bash

# ==============================================================================
# Setup and Run Script for Yii2 URL Shortener
# ==============================================================================
# Конфигурация (измените значения перед запуском)
# ==============================================================================

# URL репозитория для клонирования (оставьте пустым, если репо уже клонировано)
CLONE_URL="https://github.com/alex-kurochkin/shorting.git"

# Путь для установки проекта (если CLONE_URL не пуст, проект будет клонирован сюда)
PROJECT_ROOT="$HOME/short-yii2"

# IP и порт встроенного PHP сервера
SERVER_IP="127.0.0.1"
SERVER_PORT="8080"

# ==============================================================================
# Проверка конфигурации
# ==============================================================================

if [ -z "$CLONE_URL" ]; then
    echo "Ошибка: CLONE_URL не может быть пустым."
    exit 1
fi

if [ -z "$PROJECT_ROOT" ]; then
    echo "Ошибка: PROJECT_ROOT не может быть пустым."
    exit 1
fi

if [ -z "$SERVER_IP" ]; then
    echo "Ошибка: SERVER_IP не может быть пустым."
    exit 1
fi

if [ -z "$SERVER_PORT" ]; then
    echo "Ошибка: SERVER_PORT не может быть пустым."
    exit 1
fi

# Проверка диапазона порта
if ! [[ "$SERVER_PORT" =~ ^[0-9]+$ ]] || [ "$SERVER_PORT" -lt 1024 ] || [ "$SERVER_PORT" -gt 65535 ]; then
    echo "Ошибка: SERVER_PORT должен быть числом в диапазоне 1024-65535."
    exit 1
fi

# ==============================================================================
# Клонирование репозитория (если нужно)
# ==============================================================================

if [ ! -d "$PROJECT_ROOT" ]; then
    echo "Клонирование репозитория в $PROJECT_ROOT..."
    git clone "$CLONE_URL" "$PROJECT_ROOT"
    if [ $? -ne 0 ]; then
        echo "Ошибка: Не удалось клонировать репозиторий."
        exit 1
    fi
else
    echo "Директория $PROJECT_ROOT уже существует. Пропускаем клонирование."
fi

# Переход в директорию Yii2 проекта
cd "$PROJECT_ROOT/short-yii2" || exit 1

echo "Рабочая директория: $(pwd)"

# ==============================================================================
# Проверка зависимостей
# ==============================================================================

echo "Проверка зависимостей..."

# Проверка PHP
if ! command -v php &> /dev/null; then
    echo "Ошибка: PHP не найден. Установите PHP 8.1+."
    exit 1
fi

PHP_VERSION=$(php -r "echo PHP_VERSION;")
if version_lt "$PHP_VERSION" "8.1"; then
    echo "Ошибка: Требуется PHP 8.1 или выше. Ваша версия: $PHP_VERSION"
    exit 1
fi

# Проверка расширения pdo_sqlite
if ! php -m | grep -q "pdo_sqlite"; then
    echo "Ошибка: Расширение PHP pdo_sqlite не найдено."
    echo "Установите его: sudo apt-get install php-sqlite3 (Ubuntu/Debian) или аналогично для вашей ОС."
    exit 1
fi

# Проверка Composer
if ! command -v composer &> /dev/null; then
    echo "Ошибка: Composer не найден. Установите Composer."
    exit 1
fi

# Проверка Git
if ! command -v git &> /dev/null; then
    echo "Ошибка: Git не найден."
    exit 1
fi

echo "Все зависимости установлены корректно."

# ==============================================================================
# Установка зависимостей проекта
# ==============================================================================

echo "Установка зависимостей Composer..."
composer install --no-interaction --prefer-dist

if [ $? -ne 0 ]; then
    echo "Ошибка: Не удалось установить зависимости Composer."
    exit 1
fi

# ==============================================================================
# Настройка окружения
# ==============================================================================

ENV_FILE=".env"

if [ ! -f "$ENV_FILE" ]; then
    echo "Создание файла .env..."
    cp .env.example "$ENV_FILE"
    
    # Генерация ключа приложения
    echo "Генерация ключа приложения..."
    php yii app/key-generate
    
    # Настройка SQLite
    echo "Настройка базы данных SQLite..."
    sed -i "s|DB_DATABASE=.*|DB_DATABASE=@app/data/db.sqlite|" "$ENV_FILE"
    
    # Создание директории для БД
    mkdir -p data
    touch data/db.sqlite
    chmod 666 data/db.sqlite
else
    echo "Файл .env уже существует. Пропускаем настройку."
fi

# ==============================================================================
# Миграция базы данных
# ==============================================================================

echo "Накатывание миграций базы данных..."
php yii migrate --interactive=0

if [ $? -ne 0 ]; then
    echo "Ошибка: Не удалось накатить миграции."
    exit 1
fi

# ==============================================================================
# Запуск тестов (опционально)
# ==============================================================================

echo "Запуск тестов..."
# Для Yii2 обычно используется codeception
if [ -f "codeception.yml" ] || [ -f "codeception.dist.yml" ]; then
    ./vendor/bin/codecept run || echo "Предупреждение: Тесты завершились с ошибками, но продолжаем..."
else
    echo "Codeception не найден. Пропускаем тесты."
fi

# ==============================================================================
# Запуск встроенного PHP сервера
# ==============================================================================

echo ""
echo "=============================================================================="
echo "Проект успешно настроен!"
echo "Откройте в браузере: http://$SERVER_IP:$SERVER_PORT"
echo "Для остановки нажмите Ctrl+C"
echo "=============================================================================="
echo ""

php -S "$SERVER_IP":"$SERVER_PORT" -t web

# ==============================================================================
# Вспомогательные функции
# ==============================================================================

# Функция сравнения версий
version_lt() {
    test "$(printf '%s\n' "$@" | sort -V | head -n 1)" != "$1"
}
